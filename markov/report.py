def n(x) -> str:
    return f"{int(x):,}".replace(",", "\u202f")


def p3(x) -> str:
    return f"{x:.3f}"


def table(header: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def example_words(counter: Counter, bigram: str, k: int = 5) -> tuple[str, float]:
    """Слова (сегменты), дающие больше всего вхождений биграммы, и их доля от всех вхождений."""
    contrib = Counter()
    for w, c in counter.items():
        m = sum(1 for a, b in zip(w, w[1:]) if a + b == bigram)
        if m:
            contrib[w] += m * c
    total = sum(contrib.values())
    top = contrib.most_common(k)
    share = sum(c for _, c in top) / total if total else 0.0
    return ", ".join(f"{w} ({n(c)})" for w, c in top), share


